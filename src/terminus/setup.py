"""Interactive .env builder for the SQLite-backed TERMINUS runtime.

The runtime always opens its local SQLite file; no other database backend is
selectable. Only settings defined by :class:`terminus.config.Settings` are
written, so the generated file does not imply unsupported storage or identity
features.
"""

from __future__ import annotations

import getpass
from pathlib import Path

# Database.get_instance() always opens this relative path. Keep the wizard
# aligned with terminus.storage.db rather than advertising a backend choice.
DATABASE_FILE = "terminus.db"
LOOPBACK_HOSTS = {"127.0.0.1", "localhost", "::1"}


def _ask(prompt: str, default: str = "") -> str:
    """Read a stripped answer, falling back to the supplied default."""
    answer = input(prompt).strip()
    return answer or default


def _configure_network() -> dict[str, str]:
    """Collect the supported bind settings, defaulting to loopback."""
    print("--- STEP 2: Local service binding ----------------------------------")
    host = _ask("Bind host [127.0.0.1]: ", "127.0.0.1")
    if host not in LOOPBACK_HOSTS:
        raise ValueError("Local evaluation supports loopback binding only")
    port = _ask("Port [8000]: ", "8000")
    return {"TERMINUS_HOST": host, "TERMINUS_PORT": port}


def _configure_llm() -> dict[str, str]:
    """Collect an optional OpenAI-compatible endpoint; blank stays offline."""
    print("--- STEP 3: Model access (optional) --------------------------------")
    print("  [1] Offline/unknown only - no model key [Default]")
    print("  [2] OpenAI-compatible endpoint (including local Ollama or vLLM)")
    choice = _ask("Enter choice [1-2] (Default: 1): ", "1")
    if choice != "2":
        print(
            "[OK] No model key configured. Analysis stays offline and must be reported as unknown."
        )
        return {}

    base_url = _ask(
        "OpenAI-compatible base URL [https://api.groq.com/openai/v1]: ",
        "https://api.groq.com/openai/v1",
    )
    model = _ask("Model name [openai/gpt-oss-20b]: ", "openai/gpt-oss-20b")
    api_key = getpass.getpass("API key (leave empty to stay offline): ").strip()
    if not api_key:
        print(
            "[OK] No API key entered. Analysis stays offline and must be reported as unknown."
        )
        return {}
    return {
        "TERMINUS_LLM_BASE_URL": base_url,
        "TERMINUS_LLM_MODEL": model,
        "TERMINUS_LLM_API_KEY": api_key,
    }


def _configure_wazuh() -> dict[str, str]:
    """Collect an optional outbound Wazuh REST API target."""
    print("--- STEP 4: Wazuh REST API (optional) ------------------------------")
    print(
        "TERMINUS_WAZUH_URL is the outbound Wazuh API base URL used for queries.\nIt is not an inbound webhook; Terminus receives alerts at its own /wazuh\nroute. Leave it empty to keep SIEM lookups unavailable."
    )
    url = _ask("Wazuh API base URL (empty to skip): ")
    if not url:
        print("[OK] No Wazuh API URL configured; SIEM lookups report unavailable.")
        return {}

    user = _ask("Wazuh API username: ")
    password = getpass.getpass("Wazuh API password: ").strip()
    return {
        "TERMINUS_WAZUH_URL": url,
        "TERMINUS_WAZUH_USER": user,
        "TERMINUS_WAZUH_PASSWORD": password,
    }


def _render_env(values: dict[str, str]) -> str:
    """Render the supported settings with useful scope comments."""
    lines = [
        "# Terminus local configuration - generated by terminus-setup.",
        "# Storage is always the local SQLite file; no database URL is supported.",
        "TERMINUS_DEPLOYMENT_MODE=local",
    ]
    for name, value in values.items():
        lines.append(f"{name}={value}")
    return "\n".join(lines) + "\n"


def main() -> None:
    """Run the interactive Terminus setup wizard."""
    print("=" * 80)
    print(r"""
     _____ _____ ____  __  __ _____ _   _ _   _ ____
    |_   _| ____|  _ \|  \/  |_   _| \ | | | | / ___|
      | | |  _| | |_) | |\/| | | | |  \| | | | \___ \
      | | | |___|  _ <| |  | | | | | |\  | |_| |___) |
      |_| |_____|_| \_\_|  |_| |_| |_| \_|\___/|____/
          TERMINUS ENGINE - LOCAL CONFIGURATION BUILDER
    """)
    print("=" * 80)
    print("\nThis wizard writes supported TERMINUS_ settings to .env.")
    print("It does not create accounts, licenses or database backends.\n")

    print("--- STEP 1: Storage ------------------------------------------------")
    database_path = Path(DATABASE_FILE)
    _ = database_path.touch(exist_ok=True)
    print(f"[OK] Using the required local SQLite database: {database_path.resolve()}")
    print(
        "  PostgreSQL, MySQL, MongoDB, Redis and in-memory service backends are\n  not available. The runtime creates the schema on startup."
    )
    print()

    values: dict[str, str] = {}
    network = _configure_network()
    values.update(network)
    bind_host = network["TERMINUS_HOST"]
    bind_port = network["TERMINUS_PORT"]
    browser_host = "[::1]" if bind_host == "::1" else "127.0.0.1"
    print()
    values.update(_configure_llm())
    print()
    values.update(_configure_wazuh())
    print()

    print("--- STEP 5: Saving environment configuration (.env) ----------------")
    env_path = Path(".env")
    _ = env_path.write_text(_render_env(values), encoding="utf-8")
    print(f"[OK] Wrote supported settings to {env_path.resolve()}")

    print("\n" + "=" * 80)
    print("SETUP COMPLETE")
    print("=" * 80)
    print("\nStart the loopback evaluation service with:")
    print("  run_service.bat")
    print("\nOr directly:")
    print(
        f"  uv run --frozen uvicorn terminus.server.app:create_app --factory --host {bind_host} --port {bind_port}"
    )
    print("\nThe API does not start investigation or response workers.")
    print(
        "See docs/INSTALLATION.md for worker, source-authentication and lab boundaries."
    )
    print(f"Open the console at http://{browser_host}:{bind_port}/console/\n")


if __name__ == "__main__":
    main()
